# Free temporary public tunnel: expose local port 8080 for FunctionGraph callback.
# Usage (run in YOUR OWN PowerShell window and keep it open):
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\start_tunnel.ps1
#
# The https://xxxx.app.lhr.life in the output is BACKEND_BASE (no trailing slash).
# The free tunnel drops and rotates domains; this script reconnects automatically,
# but every new domain must be written back to the cloud function env var.
# Press Ctrl+C when done.
#
# NOTE: this exposes an unauthenticated backend to the public internet.
# Course demo only -- close it afterwards.
#
# This file is intentionally ASCII-only: Windows PowerShell 5.1 reads BOM-less
# .ps1 as ANSI/GBK, and non-ASCII characters break string parsing.

$ErrorActionPreference = 'Continue'

$lab = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$key = Join-Path $lab '.workbuddy\bin\tunnel_key_win'

# Windows OpenSSH rejects private keys with overly broad ACLs
# ("UNPROTECTED PRIVATE KEY FILE"), so use the key generated by the Windows
# ssh-keygen. The Git Bash key "tunnel_key" only works inside Git Bash.
if (-not (Test-Path $key)) {
    New-Item -ItemType Directory -Force -Path (Split-Path $key) | Out-Null
    Write-Host 'First run: generating SSH key ...' -ForegroundColor Cyan
    & ssh-keygen -t ed25519 -f $key -N '""' -q -C 'studyroom-demo'
    if (-not (Test-Path $key)) { throw 'ssh-keygen failed' }
}

Write-Host 'Connecting to localhost.run ...' -ForegroundColor Cyan
Write-Host 'The https://xxxx.app.lhr.life below is BACKEND_BASE (no trailing slash).' -ForegroundColor Yellow
Write-Host 'Domain changes on every reconnect: update BACKEND_BASE each time.' -ForegroundColor Yellow
Write-Host 'Keep this window open during the demo.' -ForegroundColor Yellow
Write-Host ''

while ($true) {
    # ssh writes its banner to stderr; with ErrorActionPreference=Stop PowerShell
    # would treat that as a terminating error and kill the reconnect loop.
    & ssh -T -n -i $key `
        -o StrictHostKeyChecking=no `
        -o UserKnownHostsFile=NUL `
        -o ServerAliveInterval=30 `
        -o ExitOnForwardFailure=yes `
        -o ConnectTimeout=15 `
        -R 80:127.0.0.1:8080 localhost.run
    Write-Host ''
    Write-Host '[TUNNEL DOWN] Reconnecting in 3s; update BACKEND_BASE with the new domain.' -ForegroundColor Yellow
    Start-Sleep -Seconds 3
}
