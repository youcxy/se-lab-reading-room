#!/usr/bin/env bash
# =============================================================================
# 在 ECS 上以 root 运行：交互式填写 FunctionGraph AK/SK，重启后端并自检。
#
#   ssh -t -i KeyPair-xxxx.pem root@<公网IP> 'bash /opt/studyroom/deploy/setup_aksk.sh'
#
# 密钥用 read -s 输入（不回显），只写进 /etc/studyroom/cloud.env（权限 600），
# 不会出现在聊天记录、命令行历史、代码仓库或日志里。
# =============================================================================
set -euo pipefail

ENV_FILE=/etc/studyroom/cloud.env
[[ $EUID -eq 0 ]] || { echo "请用 root 运行：sudo bash setup_aksk.sh"; exit 1; }

echo "=== FunctionGraph AK/SK 直调配置 ==="
echo "（输入内容只写入本机 $ENV_FILE，不会进仓库）"
echo

read -r -p "函数名 [billing-func]: " FUNC_NAME
FUNC_NAME=${FUNC_NAME:-billing-func}
read -r -p "华北-北京四 项目ID: " PROJECT_ID
read -r -s -p "AK: " AK; echo
read -r -s -p "SK: " SK; echo
read -r -p "完整函数URN（可留空，留空则按函数名自动拼接）: " FUNC_URN

if [[ -z "$PROJECT_ID" || -z "$AK" || -z "$SK" ]]; then
  echo "错误：项目ID / AK / SK 都不能为空。" >&2
  exit 1
fi

mkdir -p /etc/studyroom
umask 077
{
  echo "# Generated by setup_aksk.sh. Root-only, never commit."
  echo "FG_SDK_AK=$AK"
  echo "FG_SDK_SK=$SK"
  echo "FG_SDK_PROJECT_ID=$PROJECT_ID"
  echo "FG_SDK_FUNCTION_NAME=$FUNC_NAME"
  echo "FG_SDK_REGION=cn-north-4"
  if [[ -n "$FUNC_URN" ]]; then
    echo "FG_SDK_FUNCTION_URN=$FUNC_URN"
  fi
} > "$ENV_FILE"
chmod 600 "$ENV_FILE"
unset AK SK

echo
echo "[1/3] 已写入 $ENV_FILE（权限 $(stat -c '%a' "$ENV_FILE")）"
echo "[2/3] 重启 studyroom ..."
systemctl daemon-reload
systemctl restart studyroom

echo "[3/3] 等待后端就绪 ..."
for i in $(seq 1 30); do
  curl -fsS --max-time 3 http://127.0.0.1:8080/api/health >/dev/null 2>&1 && break
  sleep 2
done

echo
echo "--- GET /api/cloud/status ---"
curl -s --max-time 8 http://127.0.0.1/api/cloud/status; echo
echo "--- POST /api/cloud/quote (4.00 x 30) ---"
curl -s --max-time 12 -X POST -H 'Content-Type: application/json' \
  -d '{"unitPrice":4.00,"minutes":30}' http://127.0.0.1/api/cloud/quote; echo
echo
echo "判定：mode=FUNCTIONGRAPH_AKSK 且 source=CLOUD、detail 含「华为云 FunctionGraph 同步执行」即为真云端。"
echo "若 source=LOCAL，看 detail 里的错误码，对照 docs/GitHub与华为云配置步骤.md 第八章排错表。"
